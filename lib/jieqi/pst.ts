/**
 * Piece-square bonus for a piece at (x, y).
 * Red uses row (9 - y); Black mirrors vertically (row y).
 */
export function pstBonus(type: PieceType, color: "red" | "black", x: number, y: number): number {
  const row = color === "red" ? 9 - y : y;
  return TABLES[type][row][x];
}
